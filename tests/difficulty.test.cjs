'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {makeLDA}=require('./difficulty.cjs');
const game=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8').split('<script>')[1].split('</script>')[0];
const engine=new Function(game+'return {L,A,initial,step,key,won};')();
const lda=makeLDA(engine);
const rows=engine.L.map(l=>({name:l.name,...lda.analyze(l)}));
assert(rows.every(r=>r.status==='ok'&&r.score>=0&&r.score<=100));
assert.deepEqual(rows.map(r=>r.length),[3,8,10,11,4,9,10,10,10,10,7,9,8,9,9,7]);
assert.deepEqual(rows,engine.L.map(l=>({name:l.name,...lda.analyze(l)})));
const corridor=n=>({map:['##########','##########','##########','##########','#S'+'.'.repeat(n-2)+'G'+'#'.repeat(9-n),'##########'],allow:[],budget:0});
const short=lda.analyze(corridor(3)),long=lda.analyze(corridor(8));
assert.equal(short.macroSteps,long.macroSteps);
assert.equal(short.decisionBits,long.decisionBits);
assert.equal(short.deadChoiceFraction,long.deadChoiceFraction);
assert(long.score>short.score&&long.score-short.score<5);
assert(rows[15].decisionBits>0&&rows[15].deadChoiceFraction>0);
const no={...engine.L[15],laws:[]};assert.equal(lda.analyze(no).status,'unsolvable');
const c=lda.control(engine.L[15],rows[15].score);assert.equal(c.status,'matched');assert.equal(c.best.budget,1);
assert.equal(lda.control(engine.L[15],100,{tolerance:0}).status,'target-unreachable');
assert.throws(()=>makeLDA(engine,{maxStates:1}).analyze(engine.L[0]),/state limit/);
console.table(rows.map(({name,score,length,macroSteps,decisionBits,deadChoiceFraction})=>({name,score,length,macroSteps,decisionBits,deadChoiceFraction})));
console.log('LDA checks passed');
